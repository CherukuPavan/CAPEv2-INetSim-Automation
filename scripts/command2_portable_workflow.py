class WorkflowBlocked(RuntimeError):pass

def need(ok,why):
    if not ok:raise WorkflowBlocked(why)

def canonical_host(approved):
    name=socket.gethostname().split(".",1)[0].lower()
    need(name not in {"cse-ssl-55","ssl-55"} and
         not SENTINEL.exists() and not SENTINEL.is_symlink(),
         "Protected SSL-55: portable workflow forbidden")
    need(type(approved) is str and re.fullmatch(r"[a-z0-9][a-z0-9_.-]{0,62}",approved) and
         name==approved,"Approved separate-host identity mismatch")
    return name

def absolute(p,label):
    need(p is not None and p.is_absolute(),label+" must be absolute")
    return str(p)

def load_guest(journal,host,vm):
    need(journal is not None and journal.is_absolute() and
         journal.name=="command2-identity-reservation.json",
         "Exact existing Command 2 private reservation journal required")
    snapshotgate.private_evidence_folder(journal.parent)
    rows=snapshotgate.reservation_rows(journal,host)
    need(type(vm) is str and VM_RE.fullmatch(vm) is not None,
         "Select one recorded win11_1..16 guest")
    idx=int(VM_RE.fullmatch(vm).group(1))-1
    need(idx<len(rows) and rows[idx]["libvirt_name"]==vm,
         "Selected VM absent from ordered guest reservation")
    config=journal.parent/("command2-guest-config-"+vm+".json")
    # Validate original exact generated bytes, not a mutable arbitrary
    # subnet/MAC/UUID argument supplied at invocation time.
    identity.guarded_regular(config,128*1024)
    data=json.loads(config.read_text(encoding="utf-8"))
    net=ipaddress.IPv4Network(data["subnet"],strict=True)
    expected=windows.make_guest_config(rows[idx],str(net))
    need(config.read_bytes()==identity.render_config(expected),
         "Guest config mutated after reservation")
    return rows[idx],str(net),config

def choose(args):
    host=canonical_host(args.approved_host)
    phase=args.phase
    need(phase in PHASES,"Unrecognized Command 2 phase")
    need(args.mode in ("plan","apply"),"Unexpected command mode")
    need(os.geteuid()==0,"Root needed for exact private journal + host evidence")
    if args.mode=="apply":
        need(sys.stdin.isatty(),
             "Direct interactive terminal required for any host-changing phase")
    script,applymode,planmode=PHASES[phase]
    script_path=Path(__file__).resolve().with_name(script)
    need(script_path.is_file() and not script_path.is_symlink(),
         "Required pinned Command 2 phase module missing")
    mode=applymode if args.mode=="apply" else planmode
    need(mode is not None or args.mode=="plan",
         "This Command 2 acceptance phase is read-only")
    if phase=="stage":
        for key in ("disk_dir","nvram_dir","template","journal_dir"):
            absolute(getattr(args,key),key)
        need(type(args.template_sha256) is str and
             re.fullmatch(r"[0-9a-f]{64}",args.template_sha256),
             "Pinned independent Windows disk template SHA256 required")
        argv=["--mode",mode,"--approved-host",host,
              "--disk-dir",str(args.disk_dir),
              "--nvram-dir",str(args.nvram_dir),
              "--template",str(args.template),
              "--template-sha256",args.template_sha256,
              "--subnet",args.subnet or "auto",
              "--journal-dir",str(args.journal_dir)]
        if args.count is not None:
            need(type(args.count) is int and 1<=args.count<=16,
                 "VM count must be 1..16")
            argv.extend(["--count",str(args.count)])
        return script_path,argv,{"stage":"ZERO_NIC_COUNT_DRIVEN_ONLY","vm_count":args.count,
                 "guest_approval_or_boot_performed":False}

    if phase in ("snapshot-batch","cape-register","network-install","guard-persistence"):
        absolute(args.journal,"journal")
        if phase not in ("network-install","guard-persistence"):
            need(args.witness_dir is not None,"Separate private revert witness folder required")
        # Validate the target subnet using the first canonical guest config,
        # never using a caller-invented subnet.
        rows=snapshotgate.reservation_rows(args.journal,host)
        need(rows,"Empty reservation")
        vm,subnet,_=load_guest(args.journal,host,"win11_1")
        for row in rows:
            _,current,_=load_guest(args.journal,host,row["libvirt_name"])
            need(current==subnet,"Mixed guest analysis subnets refused")
        if phase in ("network-install","guard-persistence"):
            argv=["--mode",mode,"--approved-host",host,"--journal",str(args.journal)]
        else:
            argv=["--approved-host",host,"--journal",str(args.journal),
                  "--subnet",subnet,
                  "--witness-dir",absolute(args.witness_dir,"witness_dir")]
        if phase=="cape-register":
            argv=["--mode",mode,*argv,
                  "--kvm-conf",absolute(args.kvm_conf,"kvm_conf")]
        need(phase!="snapshot-batch" or args.mode=="plan",
             "Final snapshot batch audit is intentionally read-only")
        return script_path,argv,{"stage":"ALL_VM_SNAPSHOT_GATE",
                                  "vm_count":len(rows),
                                  "subnet":subnet,
                                  "not_production_release":True}

    row,subnet,config=load_guest(args.journal,host,args.vm)
    vm=row["libvirt_name"];uuid=row["libvirt_uuid_candidate"]
    mac=row["mac_candidate"];ip=row["guest_static_ipv4_target"]
    argv=["--mode",mode,"--approved-host",host,"--vm",vm]
    if phase=="identity-build":
        argv+=["--journal",str(args.journal),"--config",str(config),
               "--dest",str(args.journal.parent/(vm+".command2_identity.iso"))]
    elif phase in ("identity-attach","network-approve"):
        argv+=["--journal",str(args.journal)]
        if phase=="network-approve":
            argv+=["--receipt",absolute(args.network_receipt,"network_receipt")]
    elif phase=="identity-boot":
        argv+=["--journal",str(args.journal)]
    elif phase=="graceful-shutdown":
        need(type(args.shutdown_timeout) is int and 90<=args.shutdown_timeout<=900,
             "Graceful Windows shutdown timeout must be 90..900 seconds")
        argv+=["--scope","portable-other","--journal",str(args.journal),
               "--timeout-seconds",str(args.shutdown_timeout)]
    elif phase=="approved-firstboot":
        argv+=["--journal",str(args.journal),
               "--receipt",absolute(args.network_receipt,"network_receipt")]
    elif phase=="nic-attach":
        argv+=["--uuid",uuid,"--mac",mac,"--subnet",subnet]
        if args.mode=="apply":
            argv+=["--receipt",absolute(args.network_receipt,"network_receipt")]
        elif args.network_receipt is not None:
            argv+=["--receipt",absolute(args.network_receipt,"network_receipt")]
    elif phase.startswith("cold-"):
        argv+=["--uuid",uuid,
               "--bundle",absolute(args.recovery_bundle,"recovery_bundle")]
        if phase=="cold-restore" and args.mode=="apply":
            need(args.acknowledge_restore=="I-ACCEPT-DISPOSABLE-COLD-RESTORE-RISK",
                 "Cold restore cannot be initiated without explicit independent restore-risk acknowledgment")
            argv+=["--manifest-sha256",args.manifest_sha256 or ""]
    elif phase in ("firmware-sidecar","firmware-activate"):
        argv+=["--uuid",uuid,
               "--recovery-bundle",absolute(args.recovery_bundle,"recovery_bundle"),
               "--reviewed-manifest-sha",args.manifest_sha256 or ""]
        if phase=="firmware-activate":
            argv+=["--witness",absolute(args.firmware_restore_witness,
                                         "firmware_restore_witness"),
                   "--xml-backup-dir",absolute(args.xml_backup_dir,"xml_backup_dir")]
    elif phase=="snapshot-revert-once":
        if args.mode=="apply":
            need(args.acknowledge_revert=="I-ACCEPT-DISPOSABLE-REVERT-RISK",
                 "Explicit disposable snapshot-revert risk acknowledgment required")
        argv+=["--journal",str(args.journal),
               "--recovery-bundle",absolute(args.recovery_bundle,"recovery_bundle"),
               "--manifest-sha256",args.manifest_sha256 or ""]
    elif phase=="snapshot-capture":
        argv+=["--expected-uuid",uuid,"--expected-mac",mac,
               "--guest-ip",ip,"--subnet",subnet]
        if args.snapshot_receipt is not None:
            argv+=["--receipt",absolute(args.snapshot_receipt,"snapshot_receipt")]
        if args.mode=="apply":
            argv+=["--recovery-bundle",absolute(args.recovery_bundle,"recovery_bundle"),
                   "--reviewed-manifest-sha",args.manifest_sha256 or ""]
    else:
        raise WorkflowBlocked("Unsupported/unsafe phase")
    return script_path,argv,{"stage":phase,"vm":vm,"uuid":uuid,
                              "mac":mac,"guest_ip":ip,"subnet":subnet,
                              "master_vm_mutations_authorized":False}

def identity_batch(args):
    """Ordered batch identity-only optical preparation, not guest provisioning.

    A pure plan preflights ALL guests before the first potential mutation.
    Apply delegates to the existing individually approved ISO build and attach
    helpers through a real interactive TTY. On first failure, STOP without
    continuing or deleting any partial media/VM state.
    """
    host=canonical_host(args.approved_host)
    need(os.geteuid()==0,"Root needed for count-driven identity journal")
    need(args.vm is None,"Batch identity phase must not select one VM")
    need(args.journal is not None and args.journal.is_absolute() and
         args.journal.name=="command2-identity-reservation.json",
         "Exact absolute existing private reservation required")
    if args.mode=="apply":
        need(sys.stdin.isatty(),
             "Direct terminal required for individually approved identity operations")
    snapshotgate.private_evidence_folder(args.journal.parent)
    rows=snapshotgate.reservation_rows(args.journal,host)
    need(bool(rows),"Empty ordered reservation")
    original=hashlib.sha256(args.journal.read_bytes()).hexdigest()
    preflight=[]
    for row in rows:
        vm=row["libvirt_name"]
        _,_,config=load_guest(args.journal,host,vm)
        dest=args.journal.parent/(vm+".command2_identity.iso")
        inspection=identity.plan(host=host,vm=vm,journal=args.journal,
                                 config=config,dest=dest)
        preflight.append({"vm":vm,"uuid":row["libvirt_uuid_candidate"],
                          "planned_iso":str(dest),
                          "iso_ready":False,
                          "host_preflight":inspection["result"]})
    report={"result":"COMMAND2_BATCH_IDENTITY_PRECHECK_ONLY",
            "host":host,"vm_count":len(rows),"journal_sha256":original,
            "ordered_guests":preflight,"operation_mode":args.mode,
            "all_zero_nic_and_shut_off_at_preflight":True,
            "windows_bootstrap_task_verified":False,
            "windows_personalization_verified":False,
            "nics_or_network_changed":False,
            "guest_boots_or_snapshots_created":False,
            "command2_fully_complete":False}
    print(json.dumps(report,sort_keys=True,indent=2),flush=True)
    if args.mode=="plan":
        return 0
    for row in rows:
        vm=row["libvirt_name"]
        need(hashlib.sha256(args.journal.read_bytes()).hexdigest()==original,
             "Reservation journal changed during identity batch; STOP")
        for phase in ("identity-build","identity-attach"):
            one=argparse.Namespace(**vars(args))
            one.phase=phase
            one.vm=vm
            child,argv,details=choose(one)
            print(json.dumps({"result":"COMMAND2_BATCH_IDENTITY_STEP",
                  "vm":vm,"phase":phase,"requires_per_vm_typed_approval":True,
                  "details":details},sort_keys=True),flush=True)
            proc=subprocess.run([sys.executable,"-B",str(child),*argv],
                                check=False)
            if proc.returncode!=0:
                print(json.dumps({"result":"COMMAND2_IDENTITY_BATCH_HALTED",
                      "at_vm":vm,"at_phase":phase,"returncode":proc.returncode,
                      "partial_outputs_preserved_for_review":True,
                      "no_automatic_retry":True},sort_keys=True),
                      file=sys.stderr,flush=True)
                return 2
    print(json.dumps({"result":"COMMAND2_BATCH_IDENTITY_MEDIA_ATTACHED_ONLY",
          "vm_count":len(rows),"guest_booted":False,"static_ip_applied":False,
          "running_snapshots_created":False,"command2_complete":False},
          sort_keys=True),flush=True)
    return 0

